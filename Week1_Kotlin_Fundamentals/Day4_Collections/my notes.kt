// --------------------------------------------
// 0. List vs MutableList — مراجعة سريعة
// --------------------------------------------
// الشكل:
//   val list = listOf(1, 2, 3)          // ثابتة، مينفعش تضيف/تشيل
//   val mutable = mutableListOf(1, 2, 3) // قابلة للتعديل

// الاستخدام: listOf لبيانات مش هتتغيّر، mutableListOf لو هتضيف/تشيل عناصر
// إمتى: استخدم mutableListOf بس لو فعلاً محتاج تعديل، زي val لل var

val fixedList = listOf(1, 2, 3)
val editableList = mutableListOf(1, 2, 3)
editableList.add(4)
// fixedList.add(4)  ❌ خطأ، القائمة دي ثابتة

// ⚠️ خطأ شائع: تستخدم listOf وتحاول تعمل add عليها، هتاخد error فورًا


// --------------------------------------------
// 7. map — تحويل كل عنصر لحاجة جديدة
// --------------------------------------------
// الشكل:
//   val newList = list.map { item -> تحويل }
//   بترجع: List جديدة، بنفس عدد العناصر، لكن بعد التحويل

// الاستخدام: لما عايز "تحوّل" كل عنصر لشكل تاني (مش تفلتر، ولا تنفذ فعل بس)
// إمتى: عندك بيانات خام وعايز تجهزها بشكل تاني (نصوص منسقة مثلاً)

val grades = listOf(90, 40, 88)
val formatted = grades.map { grade -> "الدرجة: $grade" }
println(formatted)   // [الدرجة: 90, الدرجة: 40, الدرجة: 88]

// ⚠️ خطأ شائع: تستخدم map وانت عايز بس "تنفذ فعل" (زي طباعة) من غير قيمة جديدة
//    لو مش محتاج قائمة جديدة، استخدم forEach بدلها، map بتعمل عمل زيادة عبثًا


// --------------------------------------------
// 8. filter — اختيار عناصر معينة بس
// --------------------------------------------
// الشكل:
//   val newList = list.filter { item -> شرط بيرجع true/false }
//   بترجع: List جديدة فيها بس العناصر اللي الشرط تحقق فيها

// الاستخدام: لما عايز تختار جزء من القائمة بناءً على شرط
// إمتى: تصفية بيانات (زي: هات بس الطلبة الناجحين)

val passed = grades.filter { grade -> grade >= 50 }
println(passed)   // [90, 88]

// ⚠️ خطأ شائع: تلخبط بين filter و map
//    filter بتقلل عدد العناصر (بترجع true/false)
//    map بتغيّر شكل كل عنصر لكن العدد يفضل زي ما هو


// --------------------------------------------
// 9. دمج map و filter مع بعض (شائع جدًا)
// --------------------------------------------
val result = grades
    .filter { it >= 50 }
    .map { "ناجح بدرجة $it" }

println(result)   // [ناجح بدرجة 90, ناجح بدرجة 88]

// ⚠️ ملحوظة: الترتيب بيفرق أحيانًا — filter الأول أسرع لو عايز تقلل العناصر
//    قبل ما تعمل عليهم تحويل تقيل

// ============================================
// 📘 دفتر يوم 4 — Lists, Lambdas, Scope Functions
// ============================================

// --------------------------------------------
// 1. forEach — التكرار على قائمة بأسلوب حديث
// --------------------------------------------
// الشكل:
//   list.forEach { item -> ... }
//   list.forEach { println(it) }   // it = العنصر تلقائيًا لو معملتش اسم

// الاستخدام: بديل لـ for، وبيتستخدم كتير قبل map/filter
// إمتى: لما عايز "تنفذ فعل" على كل عنصر (طباعة، تسجيل...) من غير ما تحتاج نتيجة جديدة

val fruits = listOf("تفاح", "موز", "عنب")
fruits.forEach { fruit -> println("الفاكهة: $fruit") }
fruits.forEach { println("بـ it: $it") }

// ⚠️ خطأ شائع: تنسى إن forEach من غير اسم بتستخدم "it" تلقائيًا،
//    فتحاول تكتب اسم متغير غير موجود أصلاً وتاخد Unresolved reference


// --------------------------------------------
// 2. Lambda Expressions — دالة من غير اسم
// --------------------------------------------
// الشكل:
//   val name = { param: Type -> الكود }

// الاستخدام: لما محتاج "قطعة كود صغيرة" تتبعتها كقيمة لدالة تانية
// إمتى: مع forEach, map, filter, أو أي دالة بتاخد "سلوك" كمعامل

val multiply = { x: Int, y: Int -> x * y }
println(multiply(4, 5))   // 20

// ⚠️ خطأ شائع: تفتكر إن آخر سطر محتاج return — Lambda مش محتاجة return،
//    آخر سطر جواها هو القيمة المرجعة تلقائيًا


// --------------------------------------------
// 3. let — "لو القيمة موجودة، اعمل كذا"
// --------------------------------------------
// الشكل:
//   value?.let { ... }     // it = القيمة جوه الأقواس
//   بترجع: نتيجة آخر سطر

// الاستخدام: بديل أنضف لـ if (x != null) { ... }
// إمتى: مع Null Safety، لما عايز تشتغل على قيمة ممكن تكون null

val email: String? = "ahmed@test.com"
email?.let {
    println("الإيميل: $it")
    println("طوله: ${it.length}")
}

// ⚠️ خطأ شائع: تنسى علامة ال ?. قبل let، فيبقى الكود يتنفذ حتى لو القيمة null
//    الصح: value?.let { }  مش  value.let { }


// --------------------------------------------
// 4. apply — "ظبّط الكائن، وارجعه هو نفسه"
// --------------------------------------------
// الشكل:
//   val obj = ClassName(...).apply {
//       property1 = value1
//       property2 = value2
//   }
//   بترجع: نفس الكائن (بعد التعديل)

// الاستخدام: بديل أنضف لتظبيط كائن سطر سطر بعد إنشائه
// إمتى: لما عايز تعمل كائن جديد وتظبط صفاته فورًا

class Student(var name: String, var age: Int)

val student1 = Student("", 0).apply {
    name = "ahmed"
    age = 23
}

// ⚠️ خطأ شائع: تكتب it.name بدل name جوه apply
//    apply بتستخدم الصفات مباشرة، مش it (بعكس let و also)


// --------------------------------------------
// 5. also — "اعمل حاجة جانبية، وارجع الكائن زي ما هو"
// --------------------------------------------
// الشكل:
//   val obj = ClassName(...).also { println(it.property) }
//   بترجع: نفس الكائن (من غير تعديل)

// الاستخدام: طباعة/تسجيل Log وأنت مكمّل سلسلة عمليات
// إمتى: بعد ما تخلص إنشاء/تعديل كائن، وعايز "تراقب" حالته من غير ما تغيّره

val student2 = Student("sara", 21).also {
    println("طالب جديد: ${it.name}, عمره ${it.age}")
}

// دمج apply و also مع بعض (استخدام احترافي شائع)
val student3 = Student("", 0).apply {
    name = "jack"
    age = 25
}.also {
    println("تم إنشاء: ${it.name}")
}

// ⚠️ خطأ شائع: تستخدم also وانت متوقع إنها هترجع نتيجة مختلفة
//    also (زي apply) بترجع نفس الكائن دايمًا، مش نتيجة حساب


// --------------------------------------------
// 6. run — دمج بين apply و let
// --------------------------------------------
// الشكل:
//   val result = obj.run {
//       property += 1
//       "تعبير نهائي"
//   }
//   بترجع: نتيجة آخر سطر (زي let)، لكن بتستخدم الصفات مباشرة (زي apply)

// الاستخدام: لما عايز "تعدّل + تحسب نتيجة" في نفس الوقت
// إمتى: خطوة تعديل بسيطة تحتاج نتيجة نصية أو رقمية في الآخر

val summary = Student("sara", 21).run {
    age += 1
    "الطالبة $name عمرها بقى $age"
}
println(summary)

// ⚠️ خطأ شائع: تلخبط بينها وبين apply
//    apply بترجع الكائن، run بترجع نتيجة آخر سطر — لو عايز الكائن نفسه ارجع apply


// ============================================
// 🎯 الجدول الذهبي (يفرق بينهم في نظرة واحدة)
// ============================================
// | الدالة | الوصول    | بترجع        | مثالها في جملة واحدة              |
// |--------|-----------|---------------|-------------------------------------|
// | let    | it        | آخر سطر       | "لو موجودة، اعمل بيها كذا"          |
// | apply  | مباشر     | نفس الكائن    | "ظبّط الكائن ده وارجعهولي"          |
// | also   | it        | نفس الكائن    | "بلغني بس، من غير ما تغيّر حاجة"    |
// | run    | مباشر     | آخر سطر       | "عدّل واحسبلي نتيجة في نفس الوقت"   |


// ============================================
// 💡 ملاحظات إضافية وحاجات تلخبطني فيها
// ============================================
// 1. forEach و for بيعملوا نفس الحاجة بالظبط — forEach أسلوب أحدث بس
// 2. it بتظهر بس لو معرفتش اسم بنفسك في Lambda (let, also, forEach)
// 3. apply و run بيستخدموا الصفات مباشرة، من غير it — دول الاستثناء
// 4. لو نسيت هل الدالة بترجع الكائن ولا نتيجة، اسأل نفسك:
