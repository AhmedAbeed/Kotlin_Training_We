// 5. قاعدة تذكّر سريعة:
//    apply + run  → بيستخدموا الصفات مباشرة
//    let + also   → بيستخدموا it
//    apply + also → بيرجعوا نفس الكائن
//    let + run    → بيرجعوا نتيجة جديدة
