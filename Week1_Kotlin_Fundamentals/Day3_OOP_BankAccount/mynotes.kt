// ============================================
// ملحق: الدوال (Functions) — Structure كامل
// ============================================

// --------------------------------------------
// 1. الشكل العام للدالة
// --------------------------------------------
// fun اسم_الدالة(معامل: نوع, معامل2: نوع): نوع_الإرجاع { ... }

fun add(a: Int, b: Int): Int {
    return a + b
}

// fun         = بداية ثابتة لأي دالة (زي void، لكن مش بديل ليها،
//               فاكر: void بتحدد الإرجاع، fun بس بداية تعريف)
// (a: Int, ..) = المعاملات (Parameters) بأنواعها
// : Int        = نوع القيمة اللي هترجعها الدالة
// return       = القيمة الفعلية المرجعة


// --------------------------------------------
// 2. دالة من غير إرجاع (زي void في Dart)
// --------------------------------------------
// من غير ": نوع" بعد الأقواس = الدالة مترجعش حاجة (اسمها التقني: Unit)

fun greet(name: String) {
    println("أهلاً يا $name")
}

// ⚠️ ملحوظة: كتابة Unit صراحةً موجودة بس نادر تستخدمها بنفسك:
// fun greet(name: String): Unit { ... }   -- نفسها بالظبط من غير Unit


// --------------------------------------------
// 3. Expression Body (اختصار الدالة لسطر واحد)
// --------------------------------------------
// لو الدالة كلها بترجع نتيجة تعبير واحد بسيط، تقدر تختصرها بـ =

fun sum(a: Int, b: Int): Int = a + b        // بدل { return a + b }
fun sumShort(a: Int, b: Int) = a + b        // النوع بيتستنتج لوحده كمان (Int)

// ⚠️ ده بيتستخدم بس لو الدالة "سطر منطقي واحد"،
// لو فيها شروط/loops رجّعلها الصياغة الطويلة { return ... }


// --------------------------------------------
// 4. معاملات بقيمة افتراضية (Default Parameters)
// --------------------------------------------
// لو مبعتش قيمة، Kotlin بتستخدم الافتراضية

fun greetStudent(name: String, greeting: String = "أهلاً") {
    println("$greeting يا $name")
}

greetStudent("أحمد")             // أهلاً يا أحمد
greetStudent("سارة", "مرحبًا")    // مرحبًا يا سارة


// --------------------------------------------
// 5. نوع الإرجاع ممكن يكون Class إنت عامله بنفسك
// --------------------------------------------
// : Int / : String دول أنواع جاهزة من Kotlin
// لكن نفس الفكرة تنطبق على أي Class تعمله إنت (زي Account لاحقًا)

// fun createAccount(name: String, balance: Int): Account { ... }
// معناها: الدالة دي هترجع كائن كامل من نوع Account، مش رقم أو نص بس


// --------------------------------------------
// 6. Pair — إرجاع أكتر من قيمة مع بعض
// --------------------------------------------
// لما محتاج الدالة ترجع قيمتين في نفس الوقت

fun minMax(numbers: List<Int>): Pair<Int, Int> {
    return Pair(numbers.min(), numbers.max())
}

val result = minMax(listOf(5, 2, 8, 1, 9))
println("أصغر: ${result.first}, أكبر: ${result.second}")

// .first  = أول قيمة في الـ Pair
// .second = تاني قيمة في الـ Pair


// --------------------------------------------
// 7. vararg — عدد غير محدد من المعاملات
// --------------------------------------------
// بتستقبل أي عدد من القيم من نفس النوع، وبتتحط في متغير بيتعامل زي List

fun sumAll(vararg numbers: Int): Int {
    var total = 0
    for (num in numbers) total += num
    return total
}

println(sumAll(1, 2, 3))         // 6
println(sumAll(1, 2, 3, 4, 5))   // 15

// ⚠️ ملحوظة مهمة: vararg مش "الأفضل دايمًا"، هي لحالة محددة بس:
//    - لما القيم كلها من نفس النوع ونفس الدور (زي أرقام بتتجمع)
// ❌ متستخدمهاش لو كل قيمة ليها معنى مختلف (اسم، عمر، مدينة)
//    هنا الأفضل معاملات عادية: fun createAccount(name: String, age: Int)
//    عشان الوضوح + الأمان (Type Safety)


// --------------------------------------------
// 8. Local Functions — دالة جوه دالة (للاطلاع بس، مش أساسي دلوقتي)
// --------------------------------------------
fun processOrder(price: Int) {
    fun applyTax(amount: Int): Int = amount + (amount * 14 / 100)
    println("السعر النهائي: ${applyTax(price)}")
}


// ============================================
// خلاصة: إمتى تستخدم إيه
// ============================================
// - دالة عادية بترجع قيمة واحدة        → : النوع + return
// - دالة سطر واحد بسيط                 → Expression body (=)
// - دالة مترجعش حاجة (فعل بس)          → من غير : نوع (زي void)
// - قيمة ممكن تتغيّر أو تتجاهل          → Default parameter
// - عدد قيم غير معروف، نفس النوع        → vararg
// - عدد قيم ثابت، كل واحدة معناها مختلف → معاملات عادية (الأشيع والأوضح)
// - محتاج ترجع أكتر من قيمة             → Pair
