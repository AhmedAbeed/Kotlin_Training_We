// 10. State Hoisting — رفع الحالة لمستوى أعلى
// --------------------------------------------
// الشكل:
//   // المكوّن "الغبي" (بس بيعرض ويستقبل)
//   @Composable
//   fun Child(value: Int, onChange: () -> Unit) {
//       Button(onClick = onChange) { Text("$value") }
//   }

//   // المكوّن "المالك" للـ State الحقيقي
//   @Composable
//   fun Parent() {
//       var value by remember { mutableStateOf(0) }
//       Child(value = value, onChange = { value += 1 })
//   }

// الاستخدام: فصل "امتلاك الحالة" عن "عرضها فقط"
// إمتى: أي مكوّن قابل لإعادة الاستخدام في أكتر من مكان، أو محتاج تختبره بسهولة

// ⚠️ خطأ شائع: تسيب State جوه المكوّن الصغير، فيصعب مشاركته مع مكوّنات تانية


// --------------------------------------------
// 11. () -> Unit — نوع بيانات "دالة كمعامل"
// --------------------------------------------
// الشكل:
//   fun MyComponent(onClick: () -> Unit) { ... }

// الاستخدام: تبعت "فعل" كامل كمعامل، مش قيمة عادية
// إمتى: أي وقت محتاج تسمح للمكوّن "يبلّغ" اللي بره لما حاجة تحصل (زي ضغطة زرار)


// --------------------------------------------
// 12. TextField — حقل إدخال نص
// --------------------------------------------
// الشكل:
//   var text by remember { mutableStateOf("قيمة ابتدائية") }
//   TextField(
//       value = text,
//       onValueChange = { text = it }
//   )

// الاستخدام: تسمح للمستخدم يكتب/يعدّل نص
// إمتى: أي فورم أو حقل قابل للتعديل (اسم، إيميل، بحث...)

// ⚠️ خطأ شائع: تنسى onValueChange أو تسيبها فاضية،
//    فالحقل يرفض أي حرف يكتبه المستخدم (بيرجع دايمًا لقيمة value القديمة)


// --------------------------------------------
// 13. if/else جوه Compose — التبديل بين عناصر واجهة
// --------------------------------------------
// الشكل:
//   if (شرط) {
//       // اعرض عنصر UI أول
//   } else {
//       // اعرض عنصر UI تاني
//   }

// الاستخدام: تبديل شكل الشاشة بناءً على State (Boolean غالبًا)
// إمتى: زرار "تعديل" بيبدّل بين وضع العرض والتعديل، أو toggle بين حالتين

var isEditing by remember { mutableStateOf(false) }

if (isEditing) {
    TextField(value = name, onValueChange = { name = it })
} else {
    Text(text = name)
}

// ⚠️ ملحوظة: الاتنين (Text و TextField) لازم يكونوا @Composable عشان الفكرة تشتغل


// --------------------------------------------
// 14. ! (النفي المنطقي) — قلب قيمة Boolean
// --------------------------------------------
// الشكل:
//   isEditing = !isEditing

// الاستخدام: تحويل true لـ false والعكس (Toggle)
// إمتى: أي زرار بيبدّل بين حالتين (فتح/قفل، تشغيل/إيقاف، عرض/تعديل)

// ⚠️ خطأ شائع: تحاول تعمل حسابات رياضية (* -1) على Boolean، ده مش شغال خالص
//    الحل الوحيد الصح هو علامة !


// --------------------------------------------
// 15. clickable — إضافة قدرة الضغط لأي عنصر
// --------------------------------------------
// الشكل:
//   Box(modifier = Modifier.clickable { الكود اللي هيتنفذ })

// الاستخدام: تخلي أي عنصر (حتى لو مش زرار أصلًا) قابل للضغط
// إمتى: لما عندك مكوّن جاهز (زي ActionButton) معملوش onClick بنفسه من الأساس

Box(modifier = Modifier.clickable { isEditing = !isEditing }) {
    ActionButton(icon = Icons.Default.Edit, description = null)
}

// ⚠️ الأفضل: لو المكوّن بتاعك (زي ActionButton)، ضيفله onClick: () -> Unit كمعامل
//    من الأساس بدل ما تلفه بـ clickable من برّه (فاكر State Hoisting؟)


