// --------------------------------------------
// 1. @Composable — تعريف مكوّن واجهة
// --------------------------------------------
// الشكل:
//   @Composable
//   fun اسم_الدالة(معاملات اختيارية) {
//       ...
//   }

// الاستخدام: أي "قطعة واجهة" (شاشة، بطاقة، زرار مخصص) لازم تتعرّف كده
// إمتى: كل مرة عايز تعمل عنصر UI قابل لإعادة الاستخدام

@Composable
fun Greeting(name: String) {
    Text("أهلاً يا $name")
}

// ⚠️ خطأ شائع: تنسى @Composable فوق الدالة، فتظهرلك أخطاء غريبة
//    زي "Text is not a function" رغم إن الاستدعاء شكله سليم


// --------------------------------------------
// 2. Column / Row / Box — أدوات الترتيب الأساسية
// --------------------------------------------
// الشكل:
//   Column { عناصر تترتب فوق بعض عموديًا }
//   Row    { عناصر تترتب جنب بعض أفقيًا }
//   Box    { عناصر تتراكب فوق بعض في نفس المكان }

// الاستخدام: التحكم في شكل توزيع العناصر على الشاشة
// إمتى: Column لقائمة عمودية، Row لصف أفقي (زي أيقونة + نص)، Box للتراكب (زي أيقونة فوق خلفية دائرية)

Column {
    Text("سطر 1")
    Text("سطر 2")
}

Row {
    Icon(imageVector = Icons.Default.Person, contentDescription = null)
    Text("بجانب الأيقونة")
}

Box(contentAlignment = Alignment.Center) {
    // عناصر بتتراكب فوق بعض، وبتترص في النص بسبب contentAlignment
}

// ⚠️ خطأ شائع: تستخدم Column وأنت عايز عناصر جنب بعض، فتطلعلك فوق بعض بدل جنب بعض


// --------------------------------------------
// 3. Modifier — تعديل شكل وسلوك أي عنصر
// --------------------------------------------
// الشكل:
//   Modifier
//       .padding(16.dp)
//       .size(50.dp)
//       .background(Color.Gray)
//       .clip(CircleShape)

// الاستخدام: تحديد الحجم، المسافات، الألوان، الشكل (دائري/مربع) لأي عنصر
// إمتى: أي عنصر UI تقريبًا بياخد modifier كمعامل، حتى لو مش هتغيّر فيه حاجة

Box(
    modifier = Modifier
        .size(80.dp)
        .clip(CircleShape)
        .background(Color.Gray)
)

// ⚠️ خطأ شائع: ترتيب الـ modifiers بيفرق أحيانًا!
//    .padding().background()  ≠  .background().padding()
//    جرب الاتنين لو الشكل مش زي المتوقع


// --------------------------------------------
// 4. Image — عرض صورة
// --------------------------------------------
// الشكل:
//   Image(
//       painter = painterResource(R.drawable.اسم_الصورة),
//       contentDescription = "وصف للصورة (لذوي الإعاقة البصرية)"
//   )

// الاستخدام: عرض صورة من مجلد res/drawable
// إمتى: أي حاجة بصرية غير أيقونات جاهزة من مكتبة Material

Image(
    modifier = Modifier.size(50.dp).clip(CircleShape),
    painter = painterResource(R.drawable.icon),
    contentDescription = "صورة البروفايل"
)

// ⚠️ خطأ شائع: تنسى إن الصورة لازم تكون موجودة فعليًا في res/drawable بنفس الاسم،
//    وإلا هياخد error وقت البناء (build) مش وقت الكتابة


// --------------------------------------------
// 5. Scaffold — هيكل الشاشة الآمن
// --------------------------------------------
// الشكل:
//   Scaffold(modifier = Modifier.fillMaxSize()) { innerPadding ->
//       المحتوى(modifier = Modifier.padding(innerPadding))
//   }

// الاستخدام: يحسب تلقائيًا المساحة الآمنة (بعيدًا عن شريط الحالة وأزرار التنقل)
// إمتى: أي شاشة رئيسية في التطبيق، عشان المحتوى ميتغطاش بحواف الشاشة

Scaffold(modifier = Modifier.fillMaxSize()) { innerPadding ->
    HomeScreen(modifier = Modifier.padding(innerPadding))
}

// ⚠️ ملحوظة: innerPadding قيمة بيرجعها Scaffold تلقائيًا، مش إنت اللي بتحسبها


