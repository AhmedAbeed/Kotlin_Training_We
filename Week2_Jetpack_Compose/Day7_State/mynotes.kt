// --------------------------------------------
// 7. mutableStateOf / mutableIntStateOf — متغير بيبلّغ Compose
// --------------------------------------------
// الشكل:
//   val x = mutableStateOf(القيمة)      // للأنواع العامة (String, Boolean...)
//   val x = mutableIntStateOf(القيمة)   // مخصصة للأرقام الصحيحة (أداء أفضل)

// الاستخدام: أي متغير عايز Compose "تاخد باله" لما يتغيّر وتعيد الرسم
// إمتى: أي حالة (State) هتتغيّر بسبب تفاعل المستخدم (ضغط زرار، كتابة نص)

// ⚠️ خطأ شائع: تستخدم var عادي بدل مeها، فالشاشة مش بتتحدث بصريًا رغم إن القيمة اتغيرت فعليًا


// --------------------------------------------
// 8. remember — الحفاظ على القيمة عبر إعادة الرسم
// --------------------------------------------
// الشكل:
//   val x = remember { mutableStateOf(القيمة) }

// الاستخدام: لازم تحيط أي mutableStateOf بيها، وإلا القيمة بترجع لأصلها كل Recomposition
// إمتى: دايمًا مع mutableStateOf، ما فيش حالة تستخدم واحدة من غير التانية

// ⚠️ خطأ شائع: تنسى remember، فالقيمة بترجع لقيمتها الأصلية كل مرة تحصل إعادة رسم


// --------------------------------------------
// 9. by — اختصار الوصول للقيمة
